import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const root = join(scriptDirectory, "..");
const [html, css, model, app] = await Promise.all([
  readFile(join(root, "index.html"), "utf8"),
  readFile(join(root, "src", "styles.css"), "utf8"),
  readFile(join(root, "src", "model.js"), "utf8"),
  readFile(join(root, "src", "app.js"), "utf8"),
]);

const output = html
  .replace(
    '<link rel="stylesheet" href="src/styles.css">',
    `<style>\n${css}\n</style>`,
  )
  .replace(
    /  <script src="src\/model\.js"><\/script>\r?\n  <script src="src\/app\.js"><\/script>/,
    `  <script>\n${model}\n${app}\n</script>`,
  )
  .replace(
    "<!doctype html>",
    "<!doctype html>\n<!-- Generated by scripts/build-standalone.mjs. Edit index.html and src/*, then rebuild. -->",
  );

if (output.includes('src/styles.css') || output.includes('src/model.js') || output.includes('src/app.js')) {
  throw new Error("Standalone build still contains local runtime dependencies.");
}

const outputPath = join(root, "Sound_Coverage_Study_Standalone.html");
await writeFile(outputPath, output, "utf8");
console.log(`Built ${outputPath}`);

